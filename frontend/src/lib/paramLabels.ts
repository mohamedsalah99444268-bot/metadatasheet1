function humanizeKey(key: string): string {
  const s = key.replace(/^\d+_/, "").replace(/_/g, " ").trim();
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** Display label for a parameter; FR uses the map, else the backend label, else a humanised key. */
export function paramLabel(parameter: string, label: string | null | undefined, lang: Lang): string {
  if (lang === "fr") return PARAM_FR[parameter] ?? label ?? humanizeKey(parameter);
  return label ?? humanizeKey(parameter);
}

const VALUE_FR: [RegExp, string][] = [
  [/\bContinuous\b/g, "Continu"], [/\bUnlimited\b/gi, "Illimité"], [/\bYes\b/g, "Oui"], [/\bNo\b/g, "Non"],
];
/** Translate the few English words that appear inside values (e.g. "min Continuous"). */
export function valueText(text: string, lang: Lang): string {
  if (lang !== "fr") return text;
  return VALUE_FR.reduce((s, [re, fr]) => s.replace(re, fr), text);
}

/** Strip datasheet header noise ("SNOSxxx – MONTH YYYY – REVISED …") from long description values. */
export function cleanDescription(text: string): string {
  return text
    .replace(/\bS[A-Z]{3}\d{3}[A-Z]?\b\s*[-–—]?\s*/g, "")
    .replace(/\b(JANUARY|FEBRUARY|MARCH|APRIL|MAY|JUNE|JULY|AUGUST|SEPTEMBER|OCTOBER|NOVEMBER|DECEMBER)\s+\d{4}\b\s*[-–—]?\s*/gi, "")
    .replace(/\bREVISED\b\s*[-–—]?\s*/gi, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}
